_MJCF_CANDIDATES = [
    "humanoidverse/data/robots/g1/scene_29dof_freebase_mujoco.xml",
    "humanoidverse/data/robot/g1/scene_29dof_freebase_mujoco.xml",
    "humanoidverse/data/robots/g1/g1_29dof.xml",
    "humanoidverse/data/robot/g1/g1_29dof.xml",
]


def find_mjcf(repo_root: Path) -> Path:
    for rel in _MJCF_CANDIDATES:
        p = repo_root / rel
        if p.exists():
            return p
    raise FileNotFoundError(
        f"G1 MJCF not found in {repo_root}. Tried:\n  "
        + "\n  ".join(_MJCF_CANDIDATES)
        + "\nPass --mjcf explicitly."
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--recordings-dir", type=Path, help="Directory; process all *_obs.npz / *.npz files")
    src.add_argument("--files", nargs="+", type=Path, metavar="NPZ", help="Explicit list of NPZ files")
    ap.add_argument("--out-dir", type=Path, default=None,
                    help="Output directory (default: <recordings-dir>/fixed or sibling 'fixed' dir)")
    ap.add_argument("--mjcf", type=Path, default=None, help="Path to G1 MuJoCo XML (auto-detected if omitted)")
    ap.add_argument("--force", action="store_true", help="Overwrite existing *_fixed.npz files")
    ap.add_argument("--repo-root", type=Path,
                    default=Path(__file__).resolve().parents[1],
                    help="BFM-Zero repo root (default: parent of scripts/)")
    args = ap.parse_args()

    mjcf_path = args.mjcf if args.mjcf else find_mjcf(args.repo_root)
    print(f"MJCF: {mjcf_path}")

    if args.recordings_dir:
        npz_files = sorted(args.recordings_dir.glob("*_obs.npz"))
        if not npz_files:
            npz_files = sorted(args.recordings_dir.glob("*.npz"))
        if not npz_files:
            print(f"No NPZ files found in {args.recordings_dir}")
            sys.exit(1)
        out_dir = args.out_dir or (args.recordings_dir / "fixed")
    else:
        npz_files = [Path(p) for p in args.files]
        out_dir = args.out_dir or (npz_files[0].parent / "fixed")

    print(f"Processing {len(npz_files)} file(s) → {out_dir}")
    for p in npz_files:
        repair_file(p, out_dir, mjcf_path, force=args.force)

    print("\nAll done.")


if __name__ == "__main__":
    main()
