"""Repair ``privileged_state`` in recording NPZ files by recomputing it from
``qpos`` using MuJoCo Forward Kinematics, exactly replicating what the
training environment's ``compute_humanoid_observations_max`` produces.

Motivation
----------
NPZ files generated by the data-recording pipeline store a ``privileged_state``
computed via finite-difference velocities (dt = 1/30 s), which results in
velocity entries that are ~30× too large relative to the training env (which
gets cvel directly from MuJoCo at 50 Hz).  Worse, the velocity scaling makes
``backward_map`` produce a ``z`` that is biased away from the training
distribution.

This script:
  1. Loads each NPZ in ``--recordings-dir`` (or a list of explicit paths).
  2. Checks available keys.  ``qpos`` (T, 36) is the preferred source:
       qpos[:, 0:3]   — root world position (m)
       qpos[:, 3:7]   — root quaternion **wxyz** (MuJoCo convention)
       qpos[:, 7:36]  — 29 joint angles (rad, absolute)
  3. For each frame: sets MuJoCo data.qpos / data.qvel, calls mj_forward,
     extracts body world states (pos, rot, linvel, angvel).
  4. Adds the ``head_link`` extend body at
       P_head = P_torso + R_torso @ [0, 0, 0.35]   (same orientation as torso)
  5. Runs ``compute_humanoid_observations_max`` logic (pure numpy) to produce
     a (T, 463) ``privileged_state`` that is bit-compatible with the training
     environment's ``root_height_obs=True`` output.
  6. Saves a new NPZ at ``{stem}_fixed.npz`` (all original keys preserved,
     ``privileged_state`` replaced).

If ``qpos`` is absent the script tries the fallback:
  - Recovers absolute joint angles from ``state[:, :29] + DEFAULT_JOINT_POS``.
  - Recovers approximate root orientation from ``proj_grav`` (pitch/roll only;
    yaw is assumed 0 — fine for a stationary/near-stationary robot).
  - Root height is taken from ``privileged_state[:, 0]`` if available,
    otherwise defaults to the G1 standing height (0.793 m).
  The fallback produces correct LOCAL BODY POSITIONS (FK) and LOCAL
  ROTATIONS, but the heading-frame computation will have an unknown yaw error
  if the robot was not facing world +x.

Requires: numpy, scipy, mujoco  (no torch needed).

Run (server):
    python scripts/repair_recordings_privstate.py \\
        --recordings-dir data/recordings \\
        --out-dir data/recordings/fixed

    # Or for specific files:
    python scripts/repair_recordings_privstate.py \\
        --files data/recordings/g1_circle_7_obs.npz \\
                data/recordings/g1_square_4_obs.npz \\
        --out-dir data/recordings/fixed
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import mujoco
import numpy as np
from scipy.spatial.transform import Rotation as sRot

